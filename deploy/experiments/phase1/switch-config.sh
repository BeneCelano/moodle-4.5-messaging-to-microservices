#!/usr/bin/env bash
#
# Switch VM1 between the two configurations of phase 1:
#
#   C0  Moodle 4.5 untouched
#   C1  with the abstraction layer, mode=legacy
#
# The active configuration is written to disk and read back by run-campaign.sh. To run on VM1 as root.
#
#   sudo bash switch-config.sh C0|C1

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MARKER=/var/lib/phase1/active-config

if [[ ! -f "$SCRIPT_DIR/config.env" ]]; then
    echo "config.env missing: copy config.env.example and adapt it." >&2
    exit 1
fi

# shellcheck disable=SC1091
source "$SCRIPT_DIR/config.env"

CONFIG="${1:-}"
if [[ ! "$CONFIG" =~ ^(C0|C1)$ ]]; then
    echo "Usage: $0 C0|C1" >&2
    exit 1
fi

# The two configurations differ by the code tree only.
WWWROOT="$URL_DIRECT"

case "$CONFIG" in
    C0) TREE="$MOODLE_TREE_PRISTINE" ;;
    C1) TREE="$MOODLE_TREE_BRANCHED" ;;
esac

if [[ ! -d "$TREE" ]]; then
    echo "The tree $TREE does not exist." >&2
    exit 1
fi

echo "==> Configuration $CONFIG"
echo "    tree        $TREE"
echo "    wwwroot     $WWWROOT"

# The link is replaced atomically.
ln -sfn "$TREE" "${MOODLE_DOCROOT}.new"
mv -Tf "${MOODLE_DOCROOT}.new" "$MOODLE_DOCROOT"

# The settings that change between configurations live in the override file.
mkdir -p "$(dirname "$MOODLE_OVERRIDES")"
cat > "$MOODLE_OVERRIDES" <<PHP
<?php
// Generated by switch-config.sh, configuration $CONFIG, $(date -Is).
// Do not edit by hand: the next switch overwrites it.
\$CFG->wwwroot = '$WWWROOT';
\$CFG->conversationservice_mode = 'legacy';
PHP

# PHP-FPM is restarted to empty the bytecode cache.
systemctl restart "$PHP_FPM_SERVICE"
systemctl reload "$WEB_SERVICE"

# Moodle caches are purged as the web server user.
sudo -u "$WEB_USER" php "$MOODLE_DOCROOT/admin/cli/purge_caches.php" >/dev/null

# Check of the inclusion of the override file, recorded in the marker (config.php is readable by
# root only).
overrides_state() {
    local tree="$1"

    if ! grep -q 'phase1-overrides' "$tree/config.php"; then
        echo "missing"
    elif awk '/phase1-overrides/{o=NR} /require_once.*setup\.php/{s=NR} END{exit !(o>0 && s>0 && o<s)}' \
            "$tree/config.php"; then
        echo "ok"
    else
        # An inclusion after setup.php has no effect.
        echo "late"
    fi
}

mkdir -p "$(dirname "$MARKER")"
{
    echo "overrides_pristine=$(overrides_state "$MOODLE_TREE_PRISTINE")"
    echo "overrides_branched=$(overrides_state "$MOODLE_TREE_BRANCHED")"
    echo "config=$CONFIG"
    echo "tree=$TREE"
    echo "wwwroot=$WWWROOT"
    echo "switched_at=$(date -Is)"
    if [[ -d "$TREE/.git" ]]; then
        echo "revision=$(git -C "$TREE" rev-parse --short HEAD 2>/dev/null || echo unknown)"
    fi
} > "$MARKER"

echo "==> Active: $CONFIG"
